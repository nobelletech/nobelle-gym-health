package com.nobelle.core.model

import kotlinx.datetime.Instant
import kotlinx.serialization.Serializable

/** Marker groups used in My Health overview (§3). */
enum class MarkerGroup {
    ACTIVITY, ENERGY, HEART_VITALS, CARDIORESPIRATORY, SLEEP_RECOVERY,
    TEMPERATURE, BODY, BLOOD_PRESSURE, GLUCOSE, NUTRITION, RECOVERY, LABS, RECORDS,
}

/**
 * Canonical health record. Raw value/unit retained alongside normalized value (§25).
 */
@Serializable
data class HealthObservation(
    val id: String,
    val ownerUID: String,
    val marker: String,
    val group: MarkerGroup,
    val value: Double,
    val unit: String,
    val rawValue: Double? = null,
    val rawUnit: String? = null,
    val measuredUtc: Instant,
    val timeZoneOffsetSec: Int? = null,
    val provenance: Provenance,
    val method: RecordingMethod,
    val source: SourceKey? = null,
    val qualityFlag: QualityFlag = QualityFlag.OK,
    val context: Map<String, String> = emptyMap(), // fasting/meal, BP position...
    val importedUtc: Instant? = null,
    val revision: Long = 1,
    val deletedUtc: Instant? = null,
) {
    enum class QualityFlag { OK, SUSPICIOUS, IMPOSSIBLE, FUTURE_DATED, DEVICE_ESTIMATE, CONFLICTING }
}

@Serializable
data class SleepSession(
    val id: String,
    val ownerUID: String,
    val startUtc: Instant,
    val endUtc: Instant,
    val stages: List<Stage> = emptyList(),
    val source: SourceKey? = null,
    val nap: Boolean = false,
    val revision: Long = 1,
) {
    @Serializable
    data class Stage(val kind: String, val startUtc: Instant, val endUtc: Instant)
}

@Serializable
data class NutritionEntry(
    val id: String,
    val ownerUID: String,
    val loggedUtc: Instant,
    val marker: String, // water, energy, protein...
    val value: Double,
    val unit: String,
    val missing: Boolean = false, // distinguish missing from zero (§10)
    val source: SourceKey? = null,
    val revision: Long = 1,
)

@Serializable
data class LabResult(
    val id: String,
    val ownerUID: String,
    val name: String, // HbA1c, LDL, eGFR...
    val value: Double,
    val unit: String,
    val labDateUtc: Instant,
    val labReferenceRange: String? = null, // belongs to its lab/context (§10)
    val labName: String? = null,
    val provenance: Provenance,
    val attachmentId: String? = null,
    val notes: String? = null,
    val revision: Long = 1,
    val deletedUtc: Instant? = null,
)

@Serializable
data class Attachment(
    val id: String,
    val ownerUID: String,
    val fileName: String,
    val mimeType: String,
    val driveFileId: String? = null, // stored only in user's own Drive (§24)
    val retained: Boolean,
    val createdUtc: Instant,
    val revision: Long = 1,
)

/** Detection event for staged recognition features (§8). */
@Serializable
data class DetectionEvent(
    val id: String,
    val ownerUID: String,
    val detector: String,
    val modelVersion: String,
    val suggestedLabel: String,
    val confidence: Double,
    val detectedUtc: Instant,
    val status: Status = Status.SUGGESTED,
) {
    enum class Status { SUGGESTED, CONFIRMED, DISMISSED, CORRECTED }
}

@Serializable
data class UserCorrection(
    val id: String,
    val ownerUID: String,
    val targetEntityId: String,
    val field: String,
    val oldValue: String?,
    val newValue: String?,
    val correctedUtc: Instant,
)

/** Insight generated by the on-device engine; invalidated on source edits (§26). */
@Serializable
data class InsightRecord(
    val id: String,
    val ownerUID: String,
    val question: String,
    val parts: Parts,
    val sourceObservationIds: List<String>,
    val computationVersion: String,
    val knowledgeVersion: String,
    val modelVersion: String?,
    val generatedUtc: Instant,
    val rangeStartUtc: Instant,
    val rangeEndUtc: Instant,
    val stale: Boolean = false,
    val fallback: Boolean = false, // deterministic template, not model output (§26)
) {
    @Serializable
    data class Parts(
        val recordsShow: String,
        val mayMean: String,
        val nextSteps: String,
        val limits: String,
        val evidenceIds: List<String> = emptyList(),
    )
}
