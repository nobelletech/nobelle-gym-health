import { localDate, weekStart } from "../sync/history";
import { useSnapshot } from "../sync/store";

const WEEKDAY = ["Mon", "Tue", "Wed", "Thu", "Fri", "Sat", "Sun"];

export default function Plans() {
  const { snapshot } = useSnapshot();
  const plans = [...(snapshot?.trainingPlans.values() ?? [])]
    .sort((a, b) => b.weekStartDate.localeCompare(a.weekStartDate) || a.id.localeCompare(b.id));
  const thisMonday = weekStart(localDate(Date.now()));
  const current = plans.find((p) => p.weekStartDate === thisMonday) ?? plans[0];
  const isCurrentWeek = current?.weekStartDate === thisMonday;
  return (
    <>
      <h1>Plans</h1>
      <div className="card">
        <h2>Weekly plan</h2>
        <p>
          The plan synced from your phone — a suggestion you can change there, not a
          prescription. Status is read-only here; editing happens on the phone.
        </p>
        {!current ? (
          <p>No restored plans. Generate a week on the Coach tab of your phone, then restore.</p>
        ) : (
          <>
            <h3>
              Week of {current.weekStartDate}
              {isCurrentWeek ? " (current week)" : " (latest synced week)"}
            </h3>
            <p>Generated by {current.generatedBy} · {current.plannedSessions.length} sessions</p>
            {!current.plannedSessions.length ? <p>No planned sessions.</p> : (
              <div className="table-scroll"><table>
                <thead><tr><th>Day</th><th>Date</th><th>Category</th><th>Location</th><th>Status</th></tr></thead>
                <tbody>{[...current.plannedSessions].sort((a, b) => a.localDate.localeCompare(b.localDate)).map((session) => {
                  const dayMs = Date.parse(session.localDate);
                  const dow = Number.isFinite(dayMs) ? (new Date(dayMs).getUTCDay() + 6) % 7 : -1;
                  return (
                    <tr key={session.id}>
                      <td>{dow >= 0 ? WEEKDAY[dow] : "—"}</td>
                      <td>{session.localDate}</td>
                      <td>{session.category.replace(/_/g, " ")}</td>
                      <td>{session.location?.toLowerCase() ?? "—"}</td>
                      <td>{(session.status ?? "PLANNED").toLowerCase()}</td>
                    </tr>
                  );
                })}</tbody>
              </table></div>
            )}
          </>
        )}
      </div>
      <div className="card">
        <h2>Gym calendar</h2>
        <p>Attendance, planned sessions, rest days and fasting windows in one view.</p>
      </div>
    </>
  );
}
